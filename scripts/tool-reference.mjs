// Generates docs/TOOLS.md from the registered tools (names, titles, descriptions, scopes, inputs, annotations), so
// the reference never drifts from the code. Runs a Playground site with the plugin mounted and asks the registry.
// Usage: node scripts/tool-reference.mjs  (WordPress 7.1, PHP 8.3; no extra plugins needed: every tool is
// registered, availability only decides whether Claude sees it.)
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { cleanPlaygroundTemp } from './playground-temp.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'build', 'tool-reference');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const php = `<?php
require '/wordpress/wp-load.php';
require_once ABSPATH . 'wp-admin/includes/plugin.php';
activate_plugin( 'kuduy-mcp/kuduy-mcp.php' );
Kuduy\\Mcp\\Plugin::boot();
$tools = array();
foreach ( Kuduy\\Mcp\\Mcp\\ToolRegistry::create()->all() as $tool ) {
	$tools[] = array(
		'name'        => $tool->name(),
		'title'       => $tool->title(),
		'description' => $tool->description(),
		'scope'       => $tool->scope(),
		'input'       => $tool->input_schema(),
		'annotations' => $tool->annotations(),
		'class'       => get_class( $tool ),
	);
}
file_put_contents( '/kuduy-out/tools.json', wp_json_encode( $tools ) );`;

const blueprint = {
  preferredVersions: { php: '8.3', wp: '7.1' },
  steps: [
    { step: 'defineWpConfigConsts', consts: { AUTOMATIC_UPDATER_DISABLED: true } },
    { step: 'runPHP', code: php },
  ],
};
writeFileSync(join(out, 'blueprint.json'), JSON.stringify(blueprint));
const cli = join(root, 'node_modules', '@wp-playground', 'cli', 'wp-playground.js');
const run = spawnSync(process.execPath, [cli, 'run-blueprint', '--wp=7.1', '--php=8.3',
  `--blueprint=${join(out, 'blueprint.json')}`,
  '--mount-dir', root, '/wordpress/wp-content/plugins/kuduy-mcp',
  '--mount-dir', out, '/kuduy-out',
], { cwd: root, stdio: 'inherit' });
cleanPlaygroundTemp(run.pid);

const file = join(out, 'tools.json');
if (!existsSync(file)) {
  console.error('No tools.json: the Playground step did not run.');
  process.exit(1);
}
const tools = JSON.parse(readFileSync(file, 'utf8'));
const groups = new Map();
for (const t of tools) {
  const area = t.class.split('\\').slice(-2, -1)[0] || 'Core';
  if (!groups.has(area)) groups.set(area, []);
  groups.get(area).push(t);
}
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const type = (p) => (Array.isArray(p.type) ? p.type.join(' or ') : p.type ?? 'any') + (p.enum ? ` (${p.enum.join(', ')})` : '');
let md = '# KuDiagnostics — tool reference\n\n';
md += 'Generated by `node scripts/tool-reference.mjs` from the tools registered in the plugin. Do not edit by hand.\n\n';
md += `${tools.length} tools. Scope: \`kuduy:read\` ⊂ \`kuduy:write\` ⊂ \`kuduy:admin\`; \`kuduy:code\` is separate and exists only with \`KUDUY_MCP_ALLOW_CODE_EXEC\`. Every tool also checks the WordPress capability of the signed-in user, per object. Tools of plugins that are not active are not listed to Claude.\n\n`;
md += '## Contents\n\n' + [...groups.keys()].map((g) => `- [${g}](#${g.toLowerCase()})`).join('\n') + '\n\n';
for (const [area, list] of groups) {
  md += `## ${area}\n\n`;
  for (const t of list) {
    const flags = [];
    if (t.annotations?.readOnlyHint) flags.push('read only');
    if (t.annotations?.destructiveHint) flags.push('changes data (undo where noted)');
    if (t.annotations?.openWorldHint) flags.push('reaches outside the site');
    md += `### \`${t.name}\` — ${esc(t.title)}\n\n${esc(t.description)}\n\n`;
    md += `Scope \`${t.scope}\`${flags.length ? ' · ' + flags.join(' · ') : ''}\n\n`;
    const props = t.input?.properties ?? {};
    const req = new Set(t.input?.required ?? []);
    const names = Object.keys(props);
    if (names.length) {
      md += '| Input | Type | Required | Notes |\n|---|---|---|---|\n';
      for (const n of names) {
        const p = props[n] ?? {};
        md += `| \`${n}\` | ${esc(type(p))} | ${req.has(n) ? 'yes' : ''} | ${esc(p.description ?? (p.default !== undefined ? 'default ' + JSON.stringify(p.default) : ''))} |\n`;
      }
      md += '\n';
    } else {
      md += 'No input.\n\n';
    }
  }
}
writeFileSync(join(root, 'docs', 'TOOLS.md'), md);
console.log(`docs/TOOLS.md: ${tools.length} tools in ${groups.size} areas.`);
